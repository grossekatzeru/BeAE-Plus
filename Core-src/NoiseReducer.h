/*
 * NoiseReducer - "Шумодав": подавление равномерного шума (шипение, гул, вентилятор), встроенный плагин LADSPA.
 * Без зависимостей от Haiku, проверяется на Linux (tests/noise).
 *
 * Спектральное вычитание: окна по 1024 отсчёта с перекрытием 75%, БПФ, для каждой частоты считается
 * коэффициент усиления по оценке шума. Оценка шума:
 *  - Авто: следит за минимумом мощности каждой частоты за последние ~1,5 с (профиль не нужен);
 *  - По профилю: шум запоминается кнопкой "Запомнить шум" на куске, где слышен только шум.
 * Плагин вносит задержку 1024 отсчётов и сообщает её через порт "latency" (микшер её компенсирует).
 */
#ifndef NOISE_REDUCER_H
#define NOISE_REDUCER_H

#include "LadspaHost.h"

namespace NoiseReducer {

enum Port {
	P_REDUCTION = 0,	// 0..40 дБ  на сколько ослаблять шум
	P_SENSITIVITY,		// 1..4      насколько агрессивно вычитать (больше - чище, но больше артефактов)
	P_SMOOTH,			// 0..1      сглаживание (меньше "водяного" звука, но размывает атаку)
	P_USEPROFILE,		// 0/1       брать шум из запомненного профиля
	P_LEARN,			// 0/1       пока включено, запоминать шум
	P_LISTEN,			// 0/1       слушать только то, что удаляется
	P_LATENCY,			// выход: задержка в отсчётах
	P_IN_L, P_IN_R, P_OUT_L, P_OUT_R,
	P_COUNT
};

extern const float kDefaults[P_COUNT];
static const int kFrame = 1024;			// размер окна = задержка плагина

const Ladspa::Descriptor *Descriptor();

}	// namespace NoiseReducer

#endif
