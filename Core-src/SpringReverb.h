/*
 * SpringReverb - "Ламповое эхо": имитация пружинного ревербератора (встроенный плагин LADSPA).
 * Без зависимостей от Haiku, проверяется на Linux (tests/spring).
 *
 * Схема на один канал: фильтр низких (убирает басы) -> нелинейность (Dwell + Nonlinearity) ->
 * от 1 до 5 "пружин". Каждая пружина - линия задержки с обратной связью, внутри петли
 * цепочка фазовых фильтров (даёт "боинг": высокие частоты бегут быстрее низких) и фильтр
 * высоких частот. Выход пружин складывается, окрашивается регулятором Tone и смешивается с сухим.
 */
#ifndef SPRING_REVERB_H
#define SPRING_REVERB_H

#include "LadspaHost.h"

namespace SpringReverb {

enum Port {
	P_DWELL = 0,	// 0..1     подача сигнала в пружину
	P_DECAY,		// 0..1     затухание (чем больше, тем длиннее хвост)
	P_TONE,			// -1..1    тембр хвоста: темнее ... ярче
	P_MIX,			// 0..1     доля эффекта
	P_SPRINGS,		// 3..5     число пружин
	P_DELAY,		// 10..250  время круга по пружине, мс
	P_LOWCUT,		// 0..300   срез низких, Гц
	P_HIGHCUT,		// 4000..20000  срез высоких, Гц
	P_NONLIN,		// 0..1     лёгкая нелинейность (насыщение)
	P_BOING,		// 0..1     сила "боинга" (дисперсия)
	P_IN_L, P_IN_R, P_OUT_L, P_OUT_R,
	P_COUNT
};

// Значения по умолчанию (используются и для кнопки "По умолчанию").
extern const float kDefaults[P_COUNT];

const Ladspa::Descriptor *Descriptor();		// для Ladspa::RegisterBuiltin

}	// namespace SpringReverb

#endif
