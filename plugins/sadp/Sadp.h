/*
 * САДП - система адаптивного шумоподавления (приближение по описанию), плагин LADSPA без задержки.
 *
 * Односторонняя система для магнитных записей (кодирования не требуется): звук делится на полосы,
 * в каждой полосе следим за уровнем. Если в полосе нет полезного сигнала (на выходе основного сигнала
 * нет верхних или нижних частот), полоса приглушается, пока шум не слышен; как только сигнал в полосе
 * появляется, она быстро открывается. Полосы: низкие (НЧ), средние (всегда открыты), три полосы высоких.
 * Порог полосы = максимум из абсолютного порога и уровня основного сигнала минус "контраст".
 */
#ifndef SADP_H
#define SADP_H

#include "../common/ladspa_abi.h"

namespace Sadp {

enum Port {
	P_THRESHOLD = 0,	// -80..-30 дБ  абсолютный порог (уровень шума ленты)
	P_CONTRAST_HF,		// 20..60 дБ    на сколько тише основного сигнала должны быть ВЧ, чтобы считаться шумом
	P_CONTRAST_LF,		// 20..60 дБ    то же для НЧ
	P_DEPTH,			// 0..30 дБ     на сколько приглушать полосу без сигнала
	P_ATTACK,			// 1..20 мс     скорость открытия
	P_RELEASE,			// 20..1000 мс  скорость закрытия
	P_LF_EDGE,			// 50..400 Гц   граница НЧ
	P_HF_EDGE,			// 2000..8000 Гц  начало ВЧ (дальше полосы 2x и 3,5x)
	P_LISTEN,			// 0/1          слушать только удаляемое
	P_IN_L, P_IN_R, P_OUT_L, P_OUT_R,
	P_COUNT
};

const Ladspa::Descriptor *Descriptor();

}	// namespace Sadp

#endif
